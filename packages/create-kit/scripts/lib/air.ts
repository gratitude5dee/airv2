/**
 * kit/air/theme.css and kit/air/shell.css are generated from the platform's
 * theme/shell sources so the Kit can never drift from what mini.wzrd.tech
 * renders. kit/air/index.ts is hand-written (it is the Apps API client).
 */
import fs from "node:fs";
import path from "node:path";
import { THEMES, THEME_IDS, DEFAULT_THEME, tokenBlock, type ThemeId } from "../../../../apps/web/lib/miniapps/themes.ts";
import { KIT_DIR, REPO_ROOT } from "./paths.ts";
import { readText, writeText } from "./fsx.ts";

const SHELL_TS = path.join(REPO_ROOT, "apps/web/lib/miniapps/shell.ts");
const FONTS_SRC = path.join(REPO_ROOT, "apps/web/public/creator-os/fonts");
const AIR_DIR = path.join(KIT_DIR, "air");

const HEADER = (from: string) =>
  `/* GENERATED by packages/create-kit/scripts/harvest.ts from ${from}. Do not edit; edit the source and re-run harvest. */\n`;

function templateLiteral(src: string, name: string): string {
  const re = new RegExp(`const ${name} = \`([\\s\\S]*?)\`;`);
  const m = re.exec(src);
  if (!m) throw new Error(`${name} not found in shell.ts`);
  return m[1]!.replace(/\$\{([A-Z_]+)\}/g, (_all, ident: string) => stringConst(src, ident));
}

/** Value of `const IDENT = "...";` (a plain string literal, possibly wrapped onto the next line). */
function stringConst(src: string, ident: string): string {
  const m = new RegExp(`const ${ident} =\\s*"((?:[^"\\\\]|\\\\.)*)";`).exec(src);
  if (!m) throw new Error(`${ident} not found in shell.ts`);
  return m[1]!;
}

/** `:root{--a:b;--c:d}` → indented block under `selector`. */
function tokenRules(id: ThemeId, selector: string): string {
  const block = tokenBlock(THEMES[id].tokens);
  const inner = block.slice(block.indexOf("{") + 1, -1);
  const lines = inner.split(";").map((d) => `  ${d.trim()};`);
  return `${selector} {\n${lines.join("\n")}\n}\n`;
}

/** Rewrite `/creator-os/fonts/x.woff2` to a Kit-relative URL and split @font-face rules. */
function fontFaces(): string {
  const faces: string[] = [];
  for (const id of THEME_IDS) {
    const ff = THEMES[id].fontFaces;
    if (!ff) continue;
    for (const rule of ff.split("}").filter(Boolean)) {
      const local = rule.replace(/url\(\/creator-os\/fonts\//g, "url(./fonts/");
      if (!faces.includes(local + "}")) faces.push(local + "}");
    }
  }
  return faces.join("\n") + "\n";
}

function prefixLite(css: string): string {
  const out: string[] = [];
  for (const m of css.matchAll(/([^{}]+)\{([^}]*)\}/g)) {
    const selectors = m[1]!.trim().split(",").map((s) => s.trim());
    const prefixed = selectors.map((s) => (s === "html" ? 'html[data-lite="1"]' : `html[data-lite="1"] ${s}`));
    out.push(`${prefixed.join(",")}{${m[2]!.trim()}}`);
  }
  return out.join("\n") + "\n";
}

