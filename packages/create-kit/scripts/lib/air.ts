export function buildThemeCss(): string {
  const parts: string[] = [HEADER("apps/web/lib/miniapps/themes.ts")];
  parts.push("\n/* Self-hosted variable faces (font-src 'self'); served next to this file. */\n");
  parts.push(fontFaces());
  parts.push(`\n/* Themes. Default is "${DEFAULT_THEME}"; the Build Service sets <html data-theme>. */\n`);
  for (const id of THEME_IDS) {
    const selector = id === DEFAULT_THEME ? `:root,\nhtml[data-theme="${id}"]` : `html[data-theme="${id}"]`;
    parts.push(tokenRules(id, selector));
    parts.push("\n");
  }
  parts.push('/* Lite: no blur, no fixed backgrounds, no shader. Set <html data-lite="1">. */\n');
  parts.push('html[data-lite="1"] {\n  --blur: none;\n  --slide-in: none;\n}\n');
  parts.push(REDUCED_MOTION);
  parts.push(TAILWIND_BRIDGE);
  return parts.join("");
}

export function buildShellCss(): string {
  const src = readText(SHELL_TS);
  const shell = templateLiteral(src, "SHELL_CSS").trim();
  const lite = templateLiteral(src, "LITE_CSS").trim();
  return (
    HEADER("apps/web/lib/miniapps/shell.ts (SHELL_CSS + LITE_CSS)") +
    "\n/* Shell vocabulary: .frame, header.bar, .logo-pill, .app-pill, main.app, .panel, .notice,\n" +
    " * .kicker, .muted, .row, .row.actions, .item, .card, .tile, .grid, .cols, .col, .chip, .addrow,\n" +
    " * .tablewrap, .avatar, .hero, .navlink. Touch targets ≥44px; inputs ≥16px. */\n" +
    shell +
    "\n\n/* Lite variant (LITE_CSS), scoped to <html data-lite=\"1\">. */\n" +
    prefixLite(lite)
  );
}

export function writeAirAssets(): string[] {
  const changed: string[] = [];
  if (writeText(path.join(AIR_DIR, "theme.css"), buildThemeCss())) changed.push("kit/air/theme.css");
  if (writeText(path.join(AIR_DIR, "shell.css"), buildShellCss())) changed.push("kit/air/shell.css");
  fs.mkdirSync(path.join(AIR_DIR, "fonts"), { recursive: true });
  for (const f of fs.readdirSync(FONTS_SRC).sort()) {
    const src = fs.readFileSync(path.join(FONTS_SRC, f));
    const dest = path.join(AIR_DIR, "fonts", f);
    if (!fs.existsSync(dest) || !fs.readFileSync(dest).equals(src)) {
      fs.writeFileSync(dest, src);
      changed.push(`kit/air/fonts/${f}`);
    }
  }
  return changed;
}
